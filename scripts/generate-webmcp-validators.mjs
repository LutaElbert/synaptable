import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const catalogUrl = new URL('../WEBMCP_TOOL_SCHEMAS.json', import.meta.url);
const outputUrl = new URL('../app/editor/webmcp/webmcp-validators.generated.js', import.meta.url);
const catalog = JSON.parse(await readFile(catalogUrl, 'utf8'));
const catalogFingerprint = createHash('sha256')
  .update(JSON.stringify(catalog.tools.map(({ name, inputSchema }) => ({ name, inputSchema }))))
  .digest('hex');
const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  useDefaults: true,
  code: { source: true, esm: true, lines: true },
});
const schemaReferences = {};

for (const tool of catalog.tools) {
  const schemaId = `urn:synaptable:webmcp:${tool.name}`;
  ajv.addSchema({ ...tool.inputSchema, $id: schemaId }, schemaId);
  schemaReferences[tool.name] = schemaId;
}

const generated = standaloneCode(ajv, schemaReferences)
  .replace(
    /const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;\n/,
    'const $1 = ucs2Length;\n',
  );
const source = [
  '/* eslint-disable */',
  '// Generated by scripts/generate-webmcp-validators.mjs. Do not edit by hand.',
  "import ucs2LengthModule from 'ajv/dist/runtime/ucs2length.js';",
  "const ucs2Length = typeof ucs2LengthModule === 'function' ? ucs2LengthModule : ucs2LengthModule.default;",
  `export const webmcpSchemaFingerprint = '${catalogFingerprint}';`,
  generated,
].join('\n');

await writeFile(outputUrl, source);
